import assert from 'node:assert/strict';
import { writeFileSync, mkdirSync } from 'node:fs';
import { defaults, render, readme } from '../src/render';
import { profileFiles, DEMO, store } from '../src/app/data';
import { wrap, textWidth } from '../src/render/kit';

const c=defaults('whoisfazenda','ru');
c.hero.name='Имя <и> & "символы"';
c.projects.source='manual'; c.projects.repos=DEMO.all.slice(0,2).map(r=>r.name);
const original=render(c,DEMO,store,null);
assert(original['assets/hero-dark.svg'].includes('&lt;'));
assert(original['assets/hero-dark.svg'].includes('Matrix'));
assert(!original['assets/hero-dark.svg'].includes('NaN'));
assert(original['assets/hero-dark.svg'].includes('#D71920'));
assert(original['assets/hero-light.svg'].includes('#ffffff'));
const markdown=readme(c,DEMO,original);
for(const match of markdown.matchAll(/(?:src|srcset)="(assets\/[^"]+)"/g)) assert(original[match[1]],`Missing image: ${match[1]}`);
const changed=structuredClone(c); changed.seed='#3F6FB8'; changed.appearance!.radius=8; changed.appearance!.typography='essential'; changed.appearance!.speed=2; changed.appearance!.dots=false;
const custom=render(changed,DEMO,store,null);
assert.notEqual(original['assets/hero-dark.svg'],custom['assets/hero-dark.svg']);
assert(custom['assets/hero-dark.svg'].includes('#3F6FB8'));
assert(custom['assets/hero-dark.svg'].includes('rx="8"'));
assert(custom['assets/hero-dark.svg'].includes('font-family:Editorial'));
assert(custom['assets/stats-dark.svg'].includes('.dot{animation:none}'));
changed.motion=false;
const still=render(changed,DEMO,store,null)['assets/hero-dark.svg'];
assert(still.includes('*{animation:none!important}'));
assert(!still.includes('<animate '),'SMIL must stop when motion is off');
assert(wrap('x'.repeat(140),16,300,400,3).every(line=>textWidth(line,16)<=310));
const old=structuredClone(c);delete old.appearance;
assert(render(old,DEMO,store,null)['assets/hero-dark.svg'].includes('rx="19"'));
const files=profileFiles(c,DEMO,null);
assert(files['.profile/render.mjs'].includes('NOTHING INSPIRED'));
const workflow=files['.github/workflows/expressive-profile.yml'];
assert(workflow.includes('node .profile/render.mjs'));
assert(!workflow.includes('metawka/expressive-profile@'));
assert(files['.profile/FONT-LICENSES.txt'].includes('SIL OPEN FONT LICENSE'));
assert.deepEqual(JSON.parse(files['profile.json']).appearance,c.appearance);
mkdirSync('example',{recursive:true});
for(const [path,content] of Object.entries(original)){mkdirSync('example/assets',{recursive:true});writeFileSync('example/'+path,content)}
writeFileSync('example/README.md',markdown);
writeFileSync('example/profile.json',JSON.stringify(c,null,2));
console.log('PASS: themes, Cyrillic/escaping, colors, radius, typography, motion, legacy config, image references and self-contained GitHub workflow');
